@dataclass(frozen=True)
class StrategyMigration:
    source_id: str
    target_id: str
    name: str
    source_enabled: bool
    source_scope: str
    required_factors: tuple[str, ...]
    evidence_rules: int
    priority_rules: int
    approximations: tuple[str, ...]


def target_factor_id(source_factor: str) -> str:
    if source_factor == LEADER_POOL_SOURCE_FACTOR:
        return f"ext_{LEADER_POOL_CONFIG_ID}_{LEADER_POOL_FIELD}"
    if source_factor in STOCK_FACTOR_IDS:
        return f"ext_{CONFIG_ID}_{source_factor}"
    if source_factor in STRATEGY_CONTEXT_IDS:
        return f"ext_{STRATEGY_CONTEXT_CONFIG_ID}_{source_factor}"
    raise ValueError(f"策略引用尚未接入的因子: {source_factor}")


def _load_yaml(path: Path, root_key: str) -> dict[str, dict]:
    payload = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    rows = payload.get(root_key) or {}
    if not isinstance(rows, dict):
        raise ValueError(f"{path} 缺少映射节点 {root_key}")
    return rows


def _weight_rows(base: dict) -> list[dict]:
    ranking = base.get("ranking") or {}
    weights = ranking.get("prior_weights") or ranking.get("weights") or {}
    return [
        {"factor": str(factor), "weight": float(weight)}
        for factor, weight in weights.items()
        if float(weight or 0.0) != 0.0
    ]


def resolve_source_strategies(
    combinations_path: Path,
    profiles_path: Path,
) -> list[dict[str, Any]]:
    """按源 StrategyProfileRepository 的继承规则解析配置。"""
    strategies = _load_yaml(combinations_path, "strategies")
    profiles = _load_yaml(profiles_path, "screening_profiles")
    resolved: list[dict[str, Any]] = []
    for source_id, raw_value in strategies.items():
        raw = dict(raw_value or {})
        base_name = str(raw.get("base_profile") or "default")
        base = dict(profiles.get(base_name) or {})
        ranking_rows = list(raw.get("ranking_factors") or _weight_rows(base))
        required = list(
            raw["required_filters"]
            if "required_filters" in raw
            else base.get("hard_filters") or []
        )
        priority = list(
            raw["priority_filters"]
            if "priority_filters" in raw
            else base.get("priority_filters") or []
        )
        resolved.append({
            **raw,
            "id": str(source_id),
            "name": str(raw.get("name") or source_id),
            "scope": str(raw.get("scope") or "research"),
            "required_filters": required,
            "priority_filters": priority,
            "exclusion_filters": list(raw.get("exclusion_filters") or []),
            "evidence_rules": list(raw.get("evidence_rules") or []),
            "veto_rules": list(raw.get("veto_rules") or []),
            "ranking_factors": ranking_rows,
            "top_n": int(raw.get("top_n") or (base.get("ranking") or {}).get("top_n") or 10),
            "execution": dict(raw.get("execution") or {}),
        })
    return resolved


def _mapped_rules(rows: list[dict]) -> list[dict]:
    output: list[dict] = []
    for source in rows:
        rule = dict(source or {})
        operator = str(rule.get("op") or "")
        if operator not in SUPPORTED_OPERATORS:
            raise ValueError(f"不支持的策略运算符: {operator!r}")
        source_factor = str(rule.get("factor") or "")
        mapped = {
            "field": target_factor_id(source_factor),
            "source_factor": source_factor,
            "op": operator,
            "value": rule.get("value"),
            "name": str(rule.get("name") or source_factor),
        }
        for key in ("priority", "min_keep", "max_drop_ratio", "reason", "requirement"):
            if key in rule:
                mapped[key] = rule[key]
        output.append(mapped)
    return output


def _mapped_scoring(rows: list[dict]) -> tuple[dict[str, float], dict[str, str]]:
    weighted: list[tuple[str, float]] = []
    for row in rows:
        weight = float((row or {}).get("weight") or 0.0)
        if weight:
            weighted.append((target_factor_id(str(row.get("factor") or "")), weight))
    total = sum(abs(weight) for _, weight in weighted)
    if total <= 0:
        return {}, {}
    scoring = {factor: round(abs(weight) / total, 10) for factor, weight in weighted}
    directions = {factor: "low" for factor, weight in weighted if weight < 0}
    return scoring, directions


def _execution_constants(
    source: dict,
) -> tuple[float | None, int | None, tuple[tuple[float, float], ...]]:
    exit_config = (source.get("execution") or {}).get("exit") or {}
    hard_stop = exit_config.get("hard_stop_loss")
    stop_loss = -abs(float(hard_stop)) if hard_stop is not None else None
    max_hold = exit_config.get("time_stop_days")
    tiered: list[tuple[float, float]] = []
    for threshold_key, drawdown_key in (
        ("trailing_activation", "trailing_early_stop"),
        ("trailing_mid_profit", "trailing_mid_stop"),
        ("trailing_high_profit", "trailing_stop"),
    ):
        threshold = exit_config.get(threshold_key)
        drawdown = exit_config.get(drawdown_key)
        if threshold is not None and drawdown is not None:
            tiered.append((float(threshold), float(drawdown)))
    return (
        stop_loss,
        int(max_hold) if max_hold is not None else None,
        tuple(sorted(tiered)),
    )


