def migrate_strategies(
    combinations_path: Path,
    profiles_path: Path,
    data_dir: Path,
) -> list[StrategyMigration]:
    """生成策略文件和评分方向覆盖；不修改当前策略池选择。"""
    data_dir = Path(data_dir)
    destination = data_dir / "strategies" / "custom"
    destination.mkdir(parents=True, exist_ok=True)
    migrations: list[StrategyMigration] = []
    for source in resolve_source_strategies(combinations_path, profiles_path):
        code, override, migration = _render_strategy(source)
        path = destination / f"{migration.target_id}.py"
        if path.exists() and not path.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
            raise FileExistsError(f"拒绝覆盖非迁移器生成的策略: {path}")
        existing_override = strategy_config.load_override(data_dir, migration.target_id)
        if existing_override and not existing_override.get("_ass_migration"):
            raise FileExistsError(f"拒绝覆盖用户策略参数: {migration.target_id}")
        atomic_write_text(path, code)
        strategy_config.save_override(data_dir, migration.target_id, override)
        migrations.append(migration)

    engine = StrategyEngine(
        strategy_dirs=[destination],
        override_loader=lambda strategy_id: strategy_config.load_override(data_dir, strategy_id),
    )
    migrated_ids = {item.target_id for item in migrations}
    loaded_ids = {item["id"] for item in engine.list_strategies(include_research=True)}
    missing = sorted(migrated_ids - loaded_ids)
    if missing or engine.load_errors():
        raise ValueError(f"迁移策略加载失败: missing={missing}, errors={engine.load_errors()}")
    return migrations


def migrate_local_strategies(data_dir: Path) -> list[StrategyMigration]:
    """只读取仓库内已固化配置，幂等生成全部 13 个策略。"""
    root = config_dir()
    return migrate_strategies(
        root / "strategy_combinations.yaml",
        root / "strategy_profiles.yaml",
        data_dir,
    )


def verify_latest_candidates(
    data_dir: Path,
    migrations: list[StrategyMigration],
    trade_date: str,
) -> dict[str, int]:
    """在已同步扩展分区上执行生成的候选过滤，返回各策略命中数。"""
    iso_date = f"{trade_date[:4]}-{trade_date[4:6]}-{trade_date[6:]}"
    factor_path = (
        Path(data_dir) / "ext_data" / CONFIG_ID / "timeseries"
        / f"date={iso_date}" / "part.parquet"
    )
    context_path = (
        Path(data_dir) / "ext_data" / STRATEGY_CONTEXT_CONFIG_ID / "timeseries"
        / f"date={iso_date}" / "part.parquet"
    )
    factors = pl.read_parquet(factor_path).select([
        "symbol",
        *[pl.col(field).alias(target_factor_id(field)) for field in STOCK_FACTOR_IDS],
    ])
    context = pl.read_parquet(context_path).select([
        "symbol",
        *[pl.col(field).alias(target_factor_id(field)) for field in STRATEGY_CONTEXT_IDS],
    ])
    frame = factors.join(context, on="symbol", how="inner")
    leader_column = target_factor_id(LEADER_POOL_SOURCE_FACTOR)
    leader_path = (
        Path(data_dir) / "ext_data" / LEADER_POOL_CONFIG_ID / "timeseries"
        / f"date={iso_date}" / "part.parquet"
    )
    if leader_path.exists():
        leader = pl.read_parquet(leader_path).select([
            "symbol",
            pl.col(LEADER_POOL_FIELD).alias(leader_column),
        ])
        frame = frame.join(leader, on="symbol", how="left").with_columns(
            pl.col(leader_column).fill_null(0.0)
        )
    else:
        frame = frame.with_columns(pl.lit(0.0).alias(leader_column))
    destination = Path(data_dir) / "strategies" / "custom"
    engine = StrategyEngine(strategy_dirs=[destination])
    counts: dict[str, int] = {}
    for migration in migrations:
        strategy = engine.get(migration.target_id)
        if strategy is None or strategy.filter_fn is None:
            raise ValueError(f"策略不可执行: {migration.target_id}")
        expression = strategy.filter_fn(frame, {})
        candidates = frame.filter(expression)
        override = strategy_config.load_override(data_dir, migration.target_id)
        candidates = engine._apply_scoring(
            candidates,
            effective_scoring(strategy.meta.get("scoring"), override),
            effective_scoring_directions(override),
            optional_features=strategy.optional_features,
        )
        if strategy.post_score_fn is not None:
            candidates = strategy.post_score_fn(candidates, {})
        counts[migration.source_id] = candidates.height
    return counts


