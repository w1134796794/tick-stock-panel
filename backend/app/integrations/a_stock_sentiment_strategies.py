def _condition(rule: dict) -> pl.Expr:
    value = pl.col(rule["field"])
    target = rule["value"]
    operator = rule["op"]
    if operator == ">":
        return value > target
    if operator == ">=":
        return value >= target
    if operator == "<":
        return value < target
    if operator == "<=":
        return value <= target
    if operator == "==":
        return value == target
    if operator == "!=":
        return value != target
    if operator == "in":
        return value.is_in(target)
    if operator == "not in":
        return ~value.is_in(target)
    raise ValueError(f"unsupported operator: {{operator}}")


def filter(df: pl.DataFrame, params: dict) -> pl.Expr:
    del df, params
    expression = pl.lit(True)
    for rule in SOURCE_REQUIRED_FILTERS:
        expression = expression & _condition(rule)
    for rule in [*SOURCE_EXCLUSION_FILTERS, *SOURCE_VETO_RULES]:
        expression = expression & ~_condition(rule)
    return expression.fill_null(False)


